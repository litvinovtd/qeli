#!/usr/bin/env python3
"""Check/generate the compressed license catalogue used only by CLI binaries."""
import argparse
import hashlib
import json
from pathlib import Path

from native_licenses import check_bundle
from license_lz4 import compress, decompress


def expected_files(repository, windows=False):
    check_bundle(repository)
    folders = [('rust', repository / 'qeli/third-party-notices/rust')]
    if windows:
        from managed_licenses import check_bundle as check_managed
        check_managed(repository)
        folders.append(('dotnet', repository / 'qeli-shared/third-party-notices/dotnet'))
    result = {}
    for prefix, folder in folders:
        for file in folder.rglob('*'):
            if file.is_file():
                result[prefix + '/' + file.relative_to(folder).as_posix()] = file.read_bytes()
    if windows:
        result['Qeli-MPL-2.0.txt'] = (repository / 'qeli-win/LICENSE').read_bytes()
        for name, source in [('Wintun-LICENSE.txt', 'wintun/LICENSE.txt'),
                             ('WinDivert-LICENSE.txt', 'windivert/LICENSE.txt'),
                             ('WinDivert-NOTICE.txt', 'windivert/NOTICE.txt')]:
            result['drivers/' + name] = (repository / 'qeli-win/QeliWin' / source).read_bytes()
    return result


def verify_export(repository, exported, windows=False):
    expected = expected_files(repository, windows)
    paths = list(exported.rglob('*'))
    if exported.is_symlink() or any(path.is_symlink() for path in paths):
        raise ValueError('Symlink in license export')
    actual = {path.relative_to(exported).as_posix(): path.read_bytes() for path in paths if path.is_file()}
    if actual != expected:
        missing = sorted(expected.keys() - actual.keys())
        extra = sorted(actual.keys() - expected.keys())
        changed = sorted(name for name in expected.keys() & actual.keys() if expected[name] != actual[name])
        raise ValueError(f'Embedded export differs: missing={missing[:5]}, extra={extra[:5]}, changed={changed[:5]}')
    return len(expected)


def rust_resources(repository):
    check_bundle(repository)
    bundle = repository / 'qeli/third-party-notices/rust'
    entries, originals, payload, offsets = [], [], bytearray(), {}
    # Explicit component-wise ordinal case-folded order matches the original
    # catalogue on every host, independent of pathlib's OS-specific ordering.
    files = (p for p in bundle.rglob('*') if p.is_file())
    for file in sorted(files, key=lambda p: tuple(s.casefold() for s in p.relative_to(bundle).parts)):
        relative = file.relative_to(bundle).as_posix()
        if not relative.isascii() or any(p in ('', '.', '..') for p in relative.split('/')):
            raise ValueError('Unsafe embedded license name')
        data = file.read_bytes()
        if data not in offsets:
            offsets[data] = len(payload)
            payload.extend(data)
        entries.append('    (' + json.dumps('rust/' + relative) + f', {offsets[data]}, {len(data)}),')
        path = '/third-party-notices/rust/' + relative
        originals.append('    (' + json.dumps('rust/' + relative) + ', include_bytes!(concat!(env!("CARGO_MANIFEST_DIR"), ' + json.dumps(path) + '))),')
    if len(payload) > 16 * 1024 * 1024:
        raise ValueError('Legal catalogue exceeds the bounded CLI decoder limit')
    packed = compress(payload)
    if decompress(packed, len(payload)) != payload:
        raise ValueError('Compressed license round-trip failed')
    lines = ['// @generated by scripts/embedded_licenses.py --update; do not edit.',
             '// LZ4 block storage only; every exported byte remains canonical.',
             f'pub const UNPACKED_LEN: usize = {len(payload)};',
             '#[rustfmt::skip]',
             'pub const UNPACKED_SHA256: [u8; 32] = [' + ', '.join(str(b) for b in hashlib.sha256(payload).digest()) + '];',
             'pub const PACKED: &[u8] = include_bytes!("embedded_licenses.lz4");',
             '#[rustfmt::skip]',
             'pub const FILES: &[(&str, usize, usize)] = &[', *entries, '];',
             '#[cfg(test)]', '#[rustfmt::skip]',
             'pub const ORIGINALS: &[(&str, &[u8])] = &[', *originals, '];']
    return '\n'.join(lines) + '\n', packed


def rust_catalogue(repository):
    return rust_resources(repository)[0]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--repo', type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument('--update', action='store_true')
    parser.add_argument('--verify-export', type=Path)
    parser.add_argument('--windows', action='store_true')
    args = parser.parse_args()
    if args.verify_export:
        count = verify_export(args.repo, args.verify_export, args.windows)
        print(f'Embedded license export: PASS ({count} original resources)')
        return
    path = args.repo / 'qeli/src/embedded_license_files.rs'
    expected, packed = rust_resources(args.repo)
    archive = path.with_name('embedded_licenses.lz4')
    if args.update:
        from native_repro import atomic_write_bytes
        atomic_write_bytes(path, expected.encode('utf8'))
        atomic_write_bytes(archive, packed)
    if not path.is_file() or path.read_bytes().replace(b'\r\n', b'\n') != expected.encode('utf8'):
        raise SystemExit('Embedded license catalogue stale/missing; run scripts/embedded_licenses.py --update')
    if not archive.is_file() or archive.read_bytes() != packed:
        raise SystemExit('Embedded license archive stale/missing; run scripts/embedded_licenses.py --update')
    print('Embedded CLI license catalogue: PASS')


if __name__ == '__main__':
    main()
