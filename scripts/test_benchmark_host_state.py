"""Live counters are harmless; firewall semantics and missing backends are not."""
import copy
import json
from pathlib import Path
import sys
import unittest
from unittest import mock

sys.path.insert(0, str(Path(__file__).resolve().parent))
from benchmark_host_state import COMMANDS, SCHEMA, full_host_snapshot, normalize_iptables, normalize_nft, structural_host_snapshot


def fixture():
    result = {key: 'fixture' for key in COMMANDS}
    result.update(snapshot_schema=SCHEMA, nft='{"nftables":[]}')
    return result


class HostStateTests(unittest.TestCase):
    def test_real_explicit_backend_timestamp_headers_normalize(self):
        for command in ('iptables-save', 'ip6tables-save', 'iptables-nft-save', 'ip6tables-nft-save', 'iptables-legacy-save', 'ip6tables-legacy-save'):
            before = '# Generated by ' + command + ' v1.8.11 (nf_tables) on date1\n*filter\nCOMMIT'
            with self.subTest(command=command):
                self.assertEqual(normalize_iptables(before), normalize_iptables(before.replace('date1', 'date2')))

    def test_only_chain_counters_timestamp_and_diagnostic_position_normalize(self):
        warning = '# Warning: iptables-legacy tables present, use iptables-legacy-save to see them'
        original = '# Generated by iptables-save v1.8 on date1\n*filter\n:INPUT ACCEPT [1:2]\n-A INPUT -j DROP\nCOMMIT\n' + warning
        changed = warning + '\n' + original.replace('\n' + warning, '').replace('date1', 'date2').replace('[1:2]', '[3:40]')
        self.assertEqual(normalize_iptables(original), normalize_iptables(changed))
        for altered in (changed.replace('-j DROP', '-j ACCEPT'), changed.replace(':INPUT ACCEPT', ':INPUT DROP'), changed + '\n' + warning):
            self.assertNotEqual(normalize_iptables(original), normalize_iptables(altered))

    def test_rule_order_comment_and_unknown_metadata_changes_remain_visible(self):
        original = '-A INPUT -j ACCEPT\n-A INPUT -j DROP'
        for altered in ('-A INPUT -j DROP\n-A INPUT -j ACCEPT', original + '\n# unexpected warning', original + '\n-A INPUT -m comment --comment changed -j ACCEPT'):
            self.assertNotEqual(normalize_iptables(original), normalize_iptables(altered))

    def test_nft_counters_normalize_but_expression_and_named_identity_do_not(self):
        original = {'nftables': [{'rule': {'expr': [{'counter': {'packets': 1, 'bytes': 2}}, {'accept': None}]}},
                                  {'counter': {'name': 'named', 'packets': 3, 'bytes': 4}}]}
        changed = copy.deepcopy(original)
        changed['nftables'][0]['rule']['expr'][0]['counter'].update(packets=100, bytes=200)
        self.assertEqual(normalize_nft(json.dumps(original)), normalize_nft(json.dumps(changed)))
        changed['nftables'][0]['rule']['expr'][1] = {'drop': None}
        self.assertNotEqual(normalize_nft(json.dumps(original)), normalize_nft(json.dumps(changed)))
        changed = copy.deepcopy(original)
        changed['nftables'][1]['counter']['name'] = 'other'
        self.assertNotEqual(normalize_nft(json.dumps(original)), normalize_nft(json.dumps(changed)))

    def test_invalid_nft_or_counter_refuses(self):
        for text in ('{}', '{"nftables":null}', '{"nftables":[{"counter":{"packets":-1}}]}', '{"nftables":[{"counter":{"bytes":true}}]}', '{"nftables":[NaN]}'):
            with self.subTest(text=text), self.assertRaises(ValueError):
                normalize_nft(text)

    def test_missing_backend_and_changed_core_state_refuse_equality(self):
        before = fixture()
        changed = copy.deepcopy(before)
        del changed['legacy4']
        with self.assertRaisesRegex(ValueError, 'population incomplete'):
            structural_host_snapshot(changed)
        for key in ('active', 'routes', 'addresses6', 'resolver', 'namespaces', 'boot_id'):
            changed = dict(before, **{key: 'changed'})
            self.assertNotEqual(structural_host_snapshot(before), structural_host_snapshot(changed))

    def test_every_backend_is_collected_and_failure_propagates(self):
        lab = mock.Mock()
        lab.checked.side_effect = lambda command, label, timeout: '{"nftables":[]}' if command == COMMANDS['nft'] else command
        structural_host_snapshot(full_host_snapshot(lab))
        self.assertEqual(lab.checked.call_count, len(COMMANDS))
        lab.checked.side_effect = RuntimeError('legacy read refused')
        with self.assertRaisesRegex(RuntimeError, 'legacy read refused'):
            full_host_snapshot(lab)


if __name__ == '__main__':
    unittest.main()
