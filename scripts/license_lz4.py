"""Deterministic LZ4 block encoder for trusted, build-time legal resources.

No third-party codec is required by the generator or executable. Format:
https://github.com/lz4/lz4/blob/dev/doc/lz4_Block_format.md
This is storage compression, not a VPN/wire-format codec.
"""


def compress(data):
    data = bytes(data)
    output = bytearray()
    previous = {}
    anchor = position = 0

    def extension(length):
        while length >= 255:
            output.append(255)
            length -= 255
        output.append(length)

    while position <= len(data) - 12:
        key = data[position:position + 4]
        match = previous.get(key)
        previous[key] = position
        if match is None or position - match > 65535:
            position += 1
            continue
        end = position + 4
        # Leave the mandatory final five literal bytes for reference decoders.
        while end < len(data) - 5 and data[match + end - position] == data[end]:
            end += 1
        literals = position - anchor
        length = end - position - 4
        output.append((min(literals, 15) << 4) | min(length, 15))
        if literals >= 15:
            extension(literals - 15)
        output.extend(data[anchor:position])
        output.extend((position - match).to_bytes(2, 'little'))
        if length >= 15:
            extension(length - 15)
        # Greedy parsing with a deterministic four-byte match dictionary.
        for offset in range(position + 1, end):
            previous[data[offset:offset + 4]] = offset
        position = anchor = end
    literals = len(data) - anchor
    output.append(min(literals, 15) << 4)
    if literals >= 15:
        extension(literals - 15)
    output.extend(data[anchor:])
    return bytes(output)


def decompress(data, expected):
    """Independent bounded Python reader used to verify generated bytes."""
    output = bytearray()
    position = 0

    def length(seed):
        nonlocal position
        result = seed
        if seed == 15:
            while True:
                if position >= len(data):
                    raise ValueError('truncated LZ4 length')
                byte = data[position]
                position += 1
                result += byte
                if result > expected:
                    raise ValueError('LZ4 length exceeds expected output')
                if byte != 255:
                    break
        return result

    while position < len(data):
        token = data[position]
        position += 1
        literals = length(token >> 4)
        if position + literals > len(data) or len(output) + literals > expected:
            raise ValueError('invalid LZ4 literals')
        output.extend(data[position:position + literals])
        position += literals
        if position == len(data):
            break
        if position + 2 > len(data):
            raise ValueError('truncated LZ4 offset')
        offset = int.from_bytes(data[position:position + 2], 'little')
        position += 2
        count = length(token & 15) + 4
        if not offset or offset > len(output) or len(output) + count > expected:
            raise ValueError('invalid LZ4 match')
        for _ in range(count):
            output.append(output[-offset])
    if len(output) != expected:
        raise ValueError('incorrect LZ4 output length')
    return bytes(output)
