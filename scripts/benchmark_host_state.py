"""Raw snapshots and structural comparison of every Linux firewall backend."""
import json
import re

SCHEMA = 'all-firewall-v1'
COMMANDS = {
    'addresses': 'ip -br -4 addr', 'routes': 'ip -4 route show table all',
    'addresses6': 'ip -br -6 addr', 'routes6': 'ip -6 route show table all',
    'qeli_listener': 'ss -lntp | grep :443',
    'active': 'sha256sum /usr/bin/qeli; ps -C qeli -o pid,comm',
    'boot_id': 'cat /proc/sys/kernel/random/boot_id',
    'resolver': 'sha256sum /etc/resolv.conf', 'namespaces': 'ip netns list',
    'iptables4': 'iptables-save', 'iptables6': 'ip6tables-save',
    'legacy4': 'iptables-legacy-save', 'legacy6': 'ip6tables-legacy-save',
    'nft4': 'iptables-nft-save', 'nft6': 'ip6tables-nft-save',
    'nft': 'nft -j list ruleset',
}
TABLE_KEYS = ('iptables4', 'iptables6', 'legacy4', 'legacy6', 'nft4', 'nft6')
TIMESTAMP = re.compile(r'# (?:Generated by ip6?tables(?:-(?:nft|legacy))?-save .* on .+|Completed on .+)')
DIAGNOSTIC = re.compile(r"# (?:Warning: ip6?tables-legacy tables present, use ip6?tables-legacy-save to see them|Table `[^']+' (?:is incompatible, use 'nft' tool\.|contains incompatible base-chains, use 'nft' tool to list them\.))")
CHAIN = re.compile(r'(:\S+ \S+) \[([0-9]+):([0-9]+)\]')


def normalize_iptables(text):
    """Keep rule order/policies and diagnostic multiplicity; omit live counters."""
    if not isinstance(text, str):
        raise ValueError('firewall dump must be text')
    lines, diagnostics = [], []
    for line in text.splitlines():
        if TIMESTAMP.fullmatch(line):
            continue
        if DIAGNOSTIC.fullmatch(line):
            diagnostics.append(line)
            continue
        match = CHAIN.fullmatch(line)
        lines.append(match[1] + ' [COUNTERS]' if match else line)
    return dict(lines=lines, diagnostics=sorted(diagnostics))


def normalize_nft(text):
    def refuse(value):
        raise ValueError('nonfinite nft JSON ' + value)
    value = json.loads(text, parse_constant=refuse)
    if not isinstance(value, dict) or not isinstance(value.get('nftables'), list):
        raise ValueError('complete nft ruleset JSON missing')

    def visit(item, key=None):
        if isinstance(item, dict):
            result = {}
            for name, child in item.items():
                if key == 'counter' and name in ('packets', 'bytes'):
                    if type(child) is not int or child < 0:
                        raise ValueError('invalid nft live counter')
                    continue
                result[name] = visit(child, name)
            return result
        if isinstance(item, list):
            return [visit(child) for child in item]
        return item
    return visit(value)


def full_host_snapshot(lab):
    return dict(snapshot_schema=SCHEMA,
                **{key: lab.checked(command, 'full host snapshot: ' + key, timeout=20)
                   for key, command in COMMANDS.items()})


def structural_host_snapshot(snapshot):
    if not isinstance(snapshot, dict):
        raise ValueError('host snapshot must be an object')
    if 'snapshot_schema' not in snapshot:
        return snapshot  # Archived core-only snapshots retain their limited scope.
    if snapshot['snapshot_schema'] != SCHEMA or set(snapshot) != {'snapshot_schema', *COMMANDS}:
        raise ValueError('full host snapshot backend population incomplete')
    if any(not isinstance(snapshot[key], str) for key in COMMANDS):
        raise ValueError('full host snapshot field must be text')
    result = dict(snapshot)
    for key in TABLE_KEYS:
        result[key] = normalize_iptables(snapshot[key])
    result['nft'] = normalize_nft(snapshot['nft'])
    return result
